#!/usr/bin/env node
// Generates design-tokens/theme.css from design-tokens/tokens.json.
//
//   node design-tokens/scripts/build-theme.mjs          # write theme.css
//   node design-tokens/scripts/build-theme.mjs --check  # exit 1 when stale
//
// Output contract (consumed by tailwind-preset.ts, @internal/ui CSS and app CSS):
//   :root  = light palette + every non-themed token (fonts, radius, motion, layout)
//   .dark  = dark palette (the default theme, applied by the anti-flash script)
//   --color-<path>       full CSS color (backward compatible, usable everywhere)
//   --color-<path>-rgb   "r g b" channels for hex colors, used by Tailwind as
//                        rgb(var(--color-x-rgb) / <alpha-value>) so `bg-success/15` works.

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
export const tokensPath = path.resolve(here, "..", "tokens.json");
export const themePath = path.resolve(here, "..", "theme.css");

const HEX = /^#([0-9a-f]{3}|[0-9a-f]{6})$/i;

export function hexToChannels(value) {
  const match = HEX.exec(value.trim());
  if (!match) return null;
  let hex = match[1];
  if (hex.length === 3) hex = [...hex].map((c) => c + c).join("");
  const n = Number.parseInt(hex, 16);
  return `${(n >> 16) & 255} ${(n >> 8) & 255} ${n & 255}`;
}

export function flattenColors(node, prefix = []) {
  if (typeof node === "string") return [[prefix.join("-"), node]];
  return Object.entries(node).flatMap(([key, value]) => flattenColors(value, [...prefix, key]));
}

function merge(base, override) {
  const out = { ...base };
  for (const [key, value] of Object.entries(override ?? {})) {
    out[key] = typeof value === "object" && value !== null ? merge(base?.[key] ?? {}, value) : value;
  }
  return out;
}

export function themePalette(tokens, theme) {
  const light = tokens.themes?.light ?? {};
  return theme === "dark"
    ? { color: tokens.color, shadow: tokens.shadow }
    : { color: merge(tokens.color, light.color), shadow: merge(tokens.shadow, light.shadow) };
}

const cssFontList = (fonts) => fonts.map((f) => (/\s/.test(f) ? `"${f}"` : f)).join(", ");

function colorLines(colors) {
  return flattenColors(colors).flatMap(([name, value]) => {
    const lines = [`  --color-${name}: ${value};`];
    const channels = hexToChannels(value);
    if (channels) lines.push(`  --color-${name}-rgb: ${channels};`);
    return lines;
  });
}

function themeBlock(selector, scheme, palette) {
  return [
    `${selector} {`,
    `  color-scheme: ${scheme};`,
    ...colorLines(palette.color),
    ...Object.entries(palette.shadow).map(([k, v]) => `  --shadow-${k}: ${v};`),
    "}",
  ];
}

function staticLines(tokens) {
  return [
    ...Object.entries(tokens.font).map(([k, v]) => `  --font-${k}: ${cssFontList(v)};`),
    ...Object.entries(tokens.fontSize).map(([k, v]) => `  --font-size-${k}: ${v};`),
    ...Object.entries(tokens.lineHeight).map(([k, v]) => `  --line-height-${k}: ${v};`),
    ...Object.entries(tokens.radius).map(([k, v]) => `  --radius-${k}: ${v};`),
    ...Object.entries(tokens.motion).map(([k, v]) => `  --motion-${k}: ${v};`),
    ...Object.entries(tokens.layout).map(([k, v]) => `  --${k}: ${v};`),
  ];
}

export function renderThemeCss(tokens) {
  const light = themeBlock(":root", "light", themePalette(tokens, "light"));
  // Non-themed tokens live in the :root block, before its closing brace.
  light.splice(light.length - 1, 0, "", "  /* Non-themed tokens */", ...staticLines(tokens));
  return [
    "/*",
    " * theme.css - GENERATED by design-tokens/scripts/build-theme.mjs. DO NOT EDIT.",
    " * Source of truth: design-tokens/tokens.json.",
    " *",
    " * Imported once per app through @internal/design-tokens/base.css.",
    " * :root = light palette + static tokens; .dark = dark palette (default theme,",
    " * applied by the anti-flash script and ThemeToggle on <html>).",
    " * --color-<name>-rgb exposes space-separated channels for Tailwind alpha modifiers.",
    " */",
    "",
    ...light,
    "",
    ...themeBlock(".dark", "dark", themePalette(tokens, "dark")),
    "",
  ].join("\n");
}

export function readTokens() {
  return JSON.parse(readFileSync(tokensPath, "utf8"));
}

const normalize = (text) => text.replace(/\r\n/g, "\n");

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const expected = renderThemeCss(readTokens());
  if (process.argv.includes("--check")) {
    const current = normalize(readFileSync(themePath, "utf8"));
    if (current !== expected) {
      process.stderr.write("design-tokens/theme.css is stale: run `pnpm tokens:build`.\n");
      process.exit(1);
    }
    process.stdout.write("design-tokens/theme.css is up to date.\n");
  } else {
    writeFileSync(themePath, expected, "utf8");
    process.stdout.write(`Wrote ${path.relative(process.cwd(), themePath)}\n`);
  }
}
