import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const frontend = fileURLToPath(new URL("../", import.meta.url));
const backend = path.resolve(frontend, "..", "backend");
const local = path.join(backend, ".venv", process.platform === "win32" ? "Scripts" : "bin",
  process.platform === "win32" ? "python.exe" : "python");
const python = process.env.PYTHON ?? (existsSync(local) ? local : "python");
const schema = JSON.parse(execFileSync(python, ["-m", "app.openapi_export"], {
  cwd: backend, encoding: "utf8", maxBuffer: 16 * 1024 * 1024,
}));
const content = "// Generated by pnpm openapi:gen. Do not edit manually.\n" +
  astToString(await openapiTS(schema, { defaultNonNullable: false }));
const destination = path.join(frontend, "src", "types", "api.ts");
if (process.argv.includes("--check")) {
  if (!existsSync(destination) || readFileSync(destination, "utf8").replace(/\r\n/g, "\n") !== content) {
    throw new Error("OpenAPI types are stale. Run pnpm openapi:gen.");
  }
  process.stdout.write("OpenAPI types are synchronized.\n");
} else {
  mkdirSync(path.dirname(destination), { recursive: true });
  writeFileSync(destination, content);
  process.stdout.write("Generated OpenAPI types from an isolated backend schema.\n");
}
